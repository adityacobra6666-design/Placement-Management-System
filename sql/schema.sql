-- 4. Create Tables (DDL)

-- USERS Table
CREATE TABLE USERS (
    USER_ID NUMBER PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(100) NOT NULL,
    FULL_NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(30) DEFAULT 'OFFICER' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE
);

-- STUDENTS Table
CREATE TABLE STUDENTS (
    STUDENT_ID NUMBER PRIMARY KEY,
    REGISTER_NO VARCHAR2(20) NOT NULL UNIQUE,
    NAME VARCHAR2(100) NOT NULL,
    DEPARTMENT VARCHAR2(50) NOT NULL,
    CGPA NUMBER(4, 2) NOT NULL,
    BACKLOGS NUMBER(2) DEFAULT 0 NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    PHONE VARCHAR2(15),
    STATUS VARCHAR2(20) DEFAULT 'UNPLACED' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE,
    CONSTRAINT CHK_STUDENT_CGPA CHECK (CGPA >= 0.0 AND CGPA <= 10.0),
    CONSTRAINT CHK_STUDENT_BACKLOGS CHECK (BACKLOGS >= 0)
);

-- COMPANIES Table
CREATE TABLE COMPANIES (
    COMPANY_ID NUMBER PRIMARY KEY,
    COMPANY_NAME VARCHAR2(100) NOT NULL UNIQUE,
    INDUSTRY VARCHAR2(50) NOT NULL,
    LOCATION VARCHAR2(100) NOT NULL,
    HR_EMAIL VARCHAR2(100),
    HR_PHONE VARCHAR2(15),
    WEBSITE VARCHAR2(100)
);

-- PLACEMENT_DRIVES Table
CREATE TABLE PLACEMENT_DRIVES (
    DRIVE_ID NUMBER PRIMARY KEY,
    COMPANY_ID NUMBER NOT NULL,
    JOB_ROLE VARCHAR2(100) NOT NULL,
    PACKAGE_LPA NUMBER(5, 2) NOT NULL,
    MIN_CGPA NUMBER(4, 2) NOT NULL,
    MAX_BACKLOGS NUMBER(2) DEFAULT 0 NOT NULL,
    DRIVE_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT FK_DRIVE_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANIES(COMPANY_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_DRIVE_CGPA CHECK (MIN_CGPA >= 0.0 AND MIN_CGPA <= 10.0)
);

-- PLACEMENT_APPLICATIONS Table
CREATE TABLE PLACEMENT_APPLICATIONS (
    APPLICATION_ID NUMBER PRIMARY KEY,
    STUDENT_ID NUMBER NOT NULL,
    DRIVE_ID NUMBER NOT NULL,
    APPLICATION_DATE DATE DEFAULT SYSDATE,
    ELIGIBILITY_STATUS VARCHAR2(20) NOT NULL, -- 'ELIGIBLE' or 'NOT ELIGIBLE'
    STATUS VARCHAR2(20) DEFAULT 'APPLIED' NOT NULL, -- 'APPLIED', 'SHORTLISTED', 'PLACED', 'REJECTED'
    REMARKS VARCHAR2(200),
    CONSTRAINT FK_APP_STUDENT FOREIGN KEY (STUDENT_ID) REFERENCES STUDENTS(STUDENT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_APP_DRIVE FOREIGN KEY (DRIVE_ID) REFERENCES PLACEMENT_DRIVES(DRIVE_ID) ON DELETE CASCADE,
    CONSTRAINT UQ_STUDENT_DRIVE UNIQUE (STUDENT_ID, DRIVE_ID)
);

